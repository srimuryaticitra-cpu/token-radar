// The Tortoise Radar's model: one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol that records no token and is not a wrapped,
// staked or bridged product of a token that already trades (the house's own
// watchlist rule, applied to the whole snapshot, not just its floor). The
// snapshot's live-token protocols are kept apart: the board shows what a
// launch *could* be worth, the live set shows what the market already pays.
//
// Implied value is a comps model, built only from the snapshot's own figures:
//
//   comp     = the median mcap/TVL of token-bearing peers in the same
//              category, winsorized to [0.02, 1.50]; a category with fewer
//              than 3 priced peers falls back to the whole market's median
//              (0.2049 on this snapshot). No name is ever special-cased.
//   growth   = 1 + clamp(change_7d, -50, +100) / 100 * 0.60
//   maturity = 0.70 + 0.30 * min(age_days, 1095) / 1095
//              (age unknown: 0.85 — a protocol tracked a while with no token
//              has had longer to earn one; a newborn has had less)
//   breadth  = 1 + 0.05 * min(chains - 1, 6)
//   implied  = max(1, round(tvl_usd * comp * growth * maturity * breadth))
//
// A slow tortoise beats a fast hare here: TVL is the shell, the comp is the
// market's own price for that shell, growth and age are the legs, and breadth
// is how many roads the tortoise walks at once.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

